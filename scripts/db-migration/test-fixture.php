    ) ENGINE=InnoDB");
    $mysql->exec("CREATE TABLE currencies (
        code CHAR(3) NOT NULL PRIMARY KEY,
        name VARCHAR(60) NOT NULL,
        minor_units TINYINT UNSIGNED NOT NULL,
        is_active TINYINT(1) NOT NULL
    ) ENGINE=InnoDB");
