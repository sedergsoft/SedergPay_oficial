export function translate(language: Language, key: string): string {
  return extendedMessages[language][key] ?? messages[language][key] ?? extendedMessages.es[key] ?? messages.es[key] ?? key;
}

export function getInitialLanguage(): Language {
  const saved = localStorage.getItem('sederg_language');
  if (saved === 'ru' || saved === 'es') return saved;
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'es';
}
